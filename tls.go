func deriveClientKey(apiKey string) ed25519.PrivateKey {
	seed, err := hkdf.Key(sha256.New, []byte(apiKey), []byte(clientCertSalt), clientCertInfo, ed25519.SeedSize)
	if err != nil {
		panic("apex: hkdf rejected a 32-byte output: " + err.Error())
	}
	return ed25519.NewKeyFromSeed(seed)
}

func ClientPubkey(apiKey string) solana.PublicKey {
	return solana.PublicKeyFromBytes(deriveClientKey(apiKey).Public().(ed25519.PublicKey))
}

func dummyCertificate(pub ed25519.PublicKey) []byte {
	out := make([]byte, 0, len(dummyCertPrefix)+ed25519.PublicKeySize+len(dummyCertSuffix))
	out = append(out, dummyCertPrefix...)
	out = append(out, pub...)
	return append(out, dummyCertSuffix...)
}

func clientTLSConfig(key ed25519.PrivateKey, serverName string, cache tls.ClientSessionCache) *tls.Config {
	cert := &tls.Certificate{
		Certificate: [][]byte{dummyCertificate(key.Public().(ed25519.PublicKey))},
		PrivateKey:  key,
	}
	return &tls.Config{
		ServerName:         serverName,
		InsecureSkipVerify: true,
		NextProtos:         []string{alpnTPU},
		MinVersion:         tls.VersionTLS13,
		ClientSessionCache: cache,
		GetClientCertificate: func(*tls.CertificateRequestInfo) (*tls.Certificate, error) {
			return cert, nil
		},
	}
}
